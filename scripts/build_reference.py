def reason_codes() -> str:
    codes = policy.REASON_CODES + policy.EXTENDED_REASON_CODES
    missing = [c for c in codes if c not in DESCRIPTIONS]
    if missing:
        sys.exit(f"reason codes without a description in scripts/build_reference.py: {missing}")
    rows = [f"| `{c}` | {'base' if c in policy.REASON_CODES else 'extension'} | {DESCRIPTIONS[c]} |" for c in codes]
    return ("# Reason codes\n\n> Generated by `make reference` from `kym.policy`; do not edit by hand.\n\n"
            f"Decisions are one of: {', '.join(f'`{d}`' for d in policy.DECISIONS)}. Every denial carries one or more reason codes plus the failed check ids, "
            "and the same codes are stored in the evidence ledger.\n\n| Code | Kind | Meaning |\n|---|---|---|\n" + "\n".join(rows) + "\n")


def api() -> str:
    spec = app.openapi()
    groups: dict[str, list[str]] = {}
    for path, ops in sorted(spec["paths"].items()):
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            summary = (op.get("summary") or "").replace("|", "/")
            groups.setdefault(tag, []).append(f"| `{method.upper()}` | `{path}` | {summary} |")
    out = ["# HTTP API reference", "", "> Generated by `make reference` from the FastAPI OpenAPI document; do not edit by hand. "
           "The full machine-readable schema is [../specifications/openapi.json](../specifications/openapi.json) and, when the API runs, `/docs` and `/openapi.json`.",
           "", "Auth: `/bank/*` calls need a DPoP-bound access token (`Authorization: DPoP <token>` plus a `DPoP` proof header); `/api/*` calls use a demo session bearer token "
           "(`POST /api/session`, demo only). Money is always integer minor units (cents).", ""]
    for tag in sorted(groups):
        out += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|", *groups[tag], ""]
    return "\n".join(out)


(ROOT / "docs" / "reference" / "api.md").write_text(api())
(ROOT / "docs" / "reference" / "reason-codes.md").write_text(reason_codes())
